import uuid
from django.db import models
from appointments.models import Appointment
from tests_app.models import DiagnosticTest
from patients.models import PatientProfile
from accounts.models import User


def report_upload_path(instance, filename):
    return f"reports/{instance.patient.patient_id}/{filename}"


class Report(models.Model):
    class Status(models.TextChoices):
        PENDING = 'PENDING', 'Pending'
        READY = 'READY', 'Ready'

    class Origin(models.TextChoices):
        GENERATED = 'GENERATED', 'Generated by System'
        UPLOADED = 'UPLOADED', 'Uploaded by Staff'

    report_uid = models.UUIDField(default=uuid.uuid4, editable=False, unique=True)
    appointment = models.OneToOneField(Appointment, on_delete=models.CASCADE, related_name='report')
    patient = models.ForeignKey(PatientProfile, on_delete=models.CASCADE, related_name='reports')

    origin = models.CharField(max_length=10, choices=Origin.choices, default=Origin.GENERATED)
    referred_by = models.CharField(max_length=150, blank=True, help_text="e.g. 'Self' or a doctor's name, if provided.")

    is_demo_data = models.BooleanField(
        default=True,
        help_text="Tick OFF only once every result on this report is genuine. Defaults ON to prevent accidental fake-result confusion."
    )
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.PENDING)
    pdf_file = models.FileField(upload_to=report_upload_path, blank=True, null=True)

    generated_by = models.ForeignKey(
        User, on_delete=models.SET_NULL, null=True, blank=True,
        limit_choices_to={'role__in': ['STAFF', 'ADMIN']},
        related_name='reports_generated'
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Report for {self.appointment.appointment_id} — {self.patient.patient_id}"

    class Meta:
        ordering = ['-created_at']


class ReportResult(models.Model):
    class AbnormalDirection(models.TextChoices):
        NORMAL = 'NORMAL', 'Normal'
        LOW = 'LOW', 'Low'
        HIGH = 'HIGH', 'High'

    report = models.ForeignKey(Report, on_delete=models.CASCADE, related_name='results')
    test = models.ForeignKey(DiagnosticTest, on_delete=models.PROTECT, related_name='report_results')

    # Widened from CharField(255) to TextField — a single "test" (e.g. a
    # CBC panel) may genuinely need multiple analyte lines entered here.
    result_value = models.TextField(blank=True)
    reference_range = models.CharField(max_length=255, blank=True)
    units = models.CharField(max_length=50, blank=True)

    # Staff-controlled only — never inferred automatically from result_value,
    # since reference_range is free text and auto-flagging would mean the
    # system guessing at clinical significance.
    abnormal_flag = models.CharField(
        max_length=10, choices=AbnormalDirection.choices, default=AbnormalDirection.NORMAL,
        help_text="Set manually by staff if this result is outside the normal range."
    )

    class Meta:
        unique_together = [('report', 'test')]
        ordering = ['test__name']

    def __str__(self):
        return f"{self.test.name} — {self.report.appointment.appointment_id}"